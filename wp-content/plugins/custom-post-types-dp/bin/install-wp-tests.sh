#!/usr/bin/env bash
#
# Install the WordPress PHPUnit test library for this plugin.
#
# Run inside the DDEV web container:
#   ddev exec "bash wp-content/plugins/custom-post-types-dp/bin/install-wp-tests.sh"
#
# Usage: install-wp-tests.sh [db-name] [db-user] [db-pass] [db-host]
#
# The test library DROPS ALL TABLES in its database on every run, so the
# database must be a dedicated one and must never be the DDEV dev DB (`db`).
#
# Core files are read from the project's own WordPress install. The tests
# library (includes/ + data/) is fetched from wordpress-develop at the tag
# matching that core version, falling back to trunk.

set -euo pipefail

DB_NAME="${1:-wordpress_test}"
DB_USER="${2:-root}"
DB_PASS="${3:-root}"
DB_HOST="${4:-db}"

WP_TESTS_DIR="${WP_TESTS_DIR:-/tmp/wordpress-tests-lib}"
WP_CORE_DIR="${WP_CORE_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)}"

if [[ "${DB_NAME}" == "db" ]]; then
	echo "Refusing to use the dev database 'db' for tests. Pick another name." >&2
	exit 1
fi

if [[ ! -f "${WP_CORE_DIR}/wp-settings.php" ]]; then
	echo "WordPress core not found at ${WP_CORE_DIR}" >&2
	exit 1
fi

CORE_VERSION="$(grep "^\$wp_version" "${WP_CORE_DIR}/wp-includes/version.php" | sed -E "s/.*'([^']+)'.*/\1/")"
echo "Core version: ${CORE_VERSION}"

if [[ -d "${WP_TESTS_DIR}/includes" && -d "${WP_TESTS_DIR}/data" ]]; then
	echo "Tests library already present at ${WP_TESTS_DIR}, skipping download."
else
	TMP_CLONE="$(mktemp -d)"
	trap 'rm -rf "${TMP_CLONE}"' EXIT

	clone() {
		git clone --quiet --depth 1 --filter=blob:none --sparse --branch "$1" \
			https://github.com/WordPress/wordpress-develop.git "${TMP_CLONE}/src"
	}

	if ! clone "${CORE_VERSION}" 2>/dev/null; then
		echo "Tag ${CORE_VERSION} not found, using trunk."
		rm -rf "${TMP_CLONE}/src"
		clone trunk
	fi

	git -C "${TMP_CLONE}/src" sparse-checkout set tests/phpunit/includes tests/phpunit/data

	rm -rf "${WP_TESTS_DIR}"
	mkdir -p "${WP_TESTS_DIR}"
	cp -R "${TMP_CLONE}/src/tests/phpunit/includes" "${WP_TESTS_DIR}/includes"
	cp -R "${TMP_CLONE}/src/tests/phpunit/data" "${WP_TESTS_DIR}/data"
fi

cat > "${WP_TESTS_DIR}/wp-tests-config.php" <<PHP
<?php
// Generated by install-wp-tests.sh. Do not edit.
define( 'ABSPATH', '${WP_CORE_DIR}/' );
define( 'WP_DEFAULT_THEME', 'default' );
define( 'WP_DEBUG', true );

define( 'DB_NAME', '${DB_NAME}' );
define( 'DB_USER', '${DB_USER}' );
define( 'DB_PASSWORD', '${DB_PASS}' );
define( 'DB_HOST', '${DB_HOST}' );
define( 'DB_CHARSET', 'utf8' );
define( 'DB_COLLATE', '' );

define( 'AUTH_KEY', 'tests' );
define( 'SECURE_AUTH_KEY', 'tests' );
define( 'LOGGED_IN_KEY', 'tests' );
define( 'NONCE_KEY', 'tests' );
define( 'AUTH_SALT', 'tests' );
define( 'SECURE_AUTH_SALT', 'tests' );
define( 'LOGGED_IN_SALT', 'tests' );
define( 'NONCE_SALT', 'tests' );

\$table_prefix = 'wptests_';

define( 'WP_TESTS_DOMAIN', 'example.org' );
define( 'WP_TESTS_EMAIL', 'admin@example.org' );
define( 'WP_TESTS_TITLE', 'Test Blog' );
define( 'WP_PHP_BINARY', 'php' );
define( 'WPLANG', '' );
PHP

echo "Creating database ${DB_NAME} on ${DB_HOST} (if missing)."
mysql --user="${DB_USER}" --password="${DB_PASS}" --host="${DB_HOST}" \
	--execute="CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\`;"

echo "Done. Run: ddev composer --working-dir=wp-content/plugins/custom-post-types-dp test"
